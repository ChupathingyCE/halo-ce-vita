/*
CLASSIC_OPTIONS.H

Menu style Classic+'s option screens (1.1.3, the owner's Classic+ plan part B;
classic/options.xml, menu_functions.c ce_opt_*): which of the settings
panel's rows each screen shows, in order. SETTINGS' CONTROLS, GRAPHICS,
SOUND, INTERFACE, ONLINE and ADVANCED open the first six; a row that opens a
page opens one of the rest on the same screen, its parent's heading kept and
the page's name on the line under it. A row named by a panel row's variable
(or, for an action, its label) shows that row's label, values and help as the
panel has them (settings_rows.h); only the rows that open pages and SETTINGS
PANEL are Classic+'s own words. vita_settings_test.c checks every row named
here is the panel's, and that setting it keeps it in settings.txt.
*/

